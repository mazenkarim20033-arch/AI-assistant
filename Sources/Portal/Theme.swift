import SwiftUI
import UIKit

enum Theme {
    static let background = Color(red: 0.02, green: 0.02, blue: 0.04)
    static let panel = Color(red: 0.07, green: 0.07, blue: 0.10)
    static let stroke = Color.white.opacity(0.08)
    static let blue = Color(red: 0.24, green: 0.48, blue: 1.0)
    static let violet = Color(red: 0.55, green: 0.36, blue: 0.96)
    static let cyan = Color(red: 0.13, green: 0.83, blue: 0.93)
    static let secondaryText = Color.white.opacity(0.55)
}

extension View {
    /// Dark panel with a hairline border.
    func portalCard(padding: CGFloat = 16) -> some View {
        self
            .padding(padding)
            .background(Theme.panel, in: RoundedRectangle(cornerRadius: 18, style: .continuous))
            .overlay(
                RoundedRectangle(cornerRadius: 18, style: .continuous)
                    .strokeBorder(Theme.stroke, lineWidth: 1)
            )
    }
}

/// Small spaced-out caps label used for section titles.
struct SectionLabel: View {
    let text: String

    var body: some View {
        Text(text.uppercased())
            .font(.system(size: 11, weight: .semibold, design: .monospaced))
            .tracking(2)
            .foregroundStyle(Theme.cyan.opacity(0.8))
    }
}

/// Primary call-to-action: a glowing capsule.
struct PortalButtonStyle: ButtonStyle {
    func makeBody(configuration: Configuration) -> some View {
        configuration.label
            .font(.system(size: 17, weight: .semibold))
            .foregroundStyle(.white)
            .padding(.horizontal, 28)
            .padding(.vertical, 16)
            .background(
                Capsule().fill(LinearGradient(colors: [Theme.blue, Theme.violet], startPoint: .leading, endPoint: .trailing))
            )
            .shadow(color: Theme.blue.opacity(0.55), radius: configuration.isPressed ? 6 : 16)
            .scaleEffect(configuration.isPressed ? 0.97 : 1)
            .animation(.easeOut(duration: 0.15), value: configuration.isPressed)
    }
}

/// Quiet secondary button: outlined capsule.
struct GhostButtonStyle: ButtonStyle {
    func makeBody(configuration: Configuration) -> some View {
        configuration.label
            .font(.system(size: 15, weight: .medium))
            .foregroundStyle(.white.opacity(0.9))
            .padding(.horizontal, 18)
            .padding(.vertical, 12)
            .background(Capsule().strokeBorder(Color.white.opacity(0.2), lineWidth: 1))
            .opacity(configuration.isPressed ? 0.6 : 1)
    }
}

/// Where a piece of information came from. The analysis screens will label every
/// finding with one of these so guesses are never shown as facts.
enum Provenance: CaseIterable {
    case ocr, detected, vision, inferred

    var title: String {
        switch self {
        case .ocr: return "OCR"
        case .detected: return "DETECTED"
        case .vision: return "VISION MODEL"
        case .inferred: return "INFERRED"
        }
    }

    var detail: String {
        switch self {
        case .ocr: return "Text actually read from the image."
        case .detected: return "Labels from an on-device classifier, with its confidence."
        case .vision: return "A description generated by a vision model. Can be wrong."
        case .inferred: return "A conclusion the language model drew. Not verified."
        }
    }

    var color: Color {
        switch self {
        case .ocr: return Theme.cyan
        case .detected: return Theme.blue
        case .vision: return Theme.violet
        case .inferred: return Color.orange
        }
    }
}

struct ProvenanceBadge: View {
    let provenance: Provenance

    var body: some View {
        Text(provenance.title)
            .font(.system(size: 10, weight: .bold, design: .monospaced))
            .tracking(1.5)
            .foregroundStyle(provenance.color)
            .padding(.horizontal, 8)
            .padding(.vertical, 4)
            .background(provenance.color.opacity(0.15), in: Capsule())
    }
}

/// Four corner marks, like a viewfinder.
struct CornerBrackets: Shape {
    var length: CGFloat = 28

    func path(in rect: CGRect) -> Path {
        var p = Path()
        p.move(to: CGPoint(x: rect.minX, y: rect.minY + length))
        p.addLine(to: CGPoint(x: rect.minX, y: rect.minY))
        p.addLine(to: CGPoint(x: rect.minX + length, y: rect.minY))

        p.move(to: CGPoint(x: rect.maxX - length, y: rect.minY))
        p.addLine(to: CGPoint(x: rect.maxX, y: rect.minY))
        p.addLine(to: CGPoint(x: rect.maxX, y: rect.minY + length))

        p.move(to: CGPoint(x: rect.maxX, y: rect.maxY - length))
        p.addLine(to: CGPoint(x: rect.maxX, y: rect.maxY))
        p.addLine(to: CGPoint(x: rect.maxX - length, y: rect.maxY))

        p.move(to: CGPoint(x: rect.minX + length, y: rect.maxY))
        p.addLine(to: CGPoint(x: rect.minX, y: rect.maxY))
        p.addLine(to: CGPoint(x: rect.minX, y: rect.maxY - length))
        return p
    }
}

extension UIImage {
    /// Shrinks large photos so they don't waste memory. Images stay in memory only.
    func downscaled(maxDimension: CGFloat) -> UIImage {
        let longest = max(size.width, size.height)
        guard longest > maxDimension else { return self }
        let scale = maxDimension / longest
        let newSize = CGSize(width: size.width * scale, height: size.height * scale)
        let format = UIGraphicsImageRendererFormat.default()
        format.scale = 1
        return UIGraphicsImageRenderer(size: newSize, format: format).image { _ in
            draw(in: CGRect(origin: .zero, size: newSize))
        }
    }
}
